lst = [10, 20, 30, 40, 50]

# Indexing
print(lst[0])    # 10
print(lst[-1])   # 50 (last element)

# Slicing
print(lst[1:4])  # [20, 30, 40]
print(lst[::2])  # [10, 30, 50] (step of 2)

print(lst[-2]) # 50 (last element)
